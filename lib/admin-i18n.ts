export function translateAdminString(input: string): string {
  let out = input
  for (const [en, zh] of ADMIN_ZH) {
    if (out.includes(en)) {
      if (/^[A-Za-z][A-Za-z0-9]*$/.test(en)) {
        // Single-word keys: match whole words only (avoids "Read" inside "Ready")
        out = out.replace(new RegExp(`\\b${en}\\b`, "g"), zh)
      } else {
        out = out.split(en).join(zh)
      }
    }
  }
  return out
}

export function applyAdminChinese(root: Node = document.body): void {
  // Translate placeholder / title / aria-label attributes
  const attrEls = (root as Element).querySelectorAll
    ? (root as Element).querySelectorAll<HTMLElement>("input, textarea, select, [placeholder], [title], [aria-label]")
    : []
  attrEls.forEach(el => {
    if (el.closest("[data-admin-lang-ignore]")) return
    for (const attr of ["placeholder", "title", "aria-label"] as const) {
      const v = el.getAttribute(attr)
      if (v) {
        const nv = translateAdminString(v)
        if (nv !== v) el.setAttribute(attr, nv)
      }
    }
  })

  // Translate text nodes
  const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT, {
    acceptNode(node) {
      const parent = node.parentElement
      if (!parent || parent.closest("[data-admin-lang-ignore]") || parent.tagName === "SCRIPT" || parent.tagName === "STYLE") {
        return NodeFilter.FILTER_REJECT
      }
      return NodeFilter.FILTER_ACCEPT
    },
  })
  const nodes: Text[] = []
  while (walker.nextNode()) nodes.push(walker.currentNode as Text)
  nodes.forEach(n => {
    const orig = n.nodeValue || ""
    if (!orig.trim()) return
    const nv = translateAdminString(orig)
    if (nv !== orig) n.nodeValue = nv
  })
}
